import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {compactPlayerMap,buildTrends,collectTrends,validTrendFeed,TREND_LIMIT} from './refresh-sleeper-trends.mjs';

const now=Date.now(),raw=Object.fromEntries(Array.from({length:120},(_,i)=>[String(i+1),{player_id:String(i+1),espn_id:i+1001,full_name:'Test Player '+i,position:'RB',team:'DET'}]));
raw.DET={player_id:'DET',full_name:'Detroit Lions',position:'DEF',team:'DET'};
raw.idp={player_id:'idp',full_name:'Test Linebacker',position:'LB',team:'DET'};
const map=compactPlayerMap(raw,now);map.ignoredIds=['idp'];
const adds=[{player_id:'1',count:5500000},{player_id:'2',count:200},{player_id:'DET',count:800},{player_id:'idp',count:5}];
const drops=[{player_id:'1',count:1100000},{player_id:'2',count:1100200},{player_id:'DET',count:100}];
const feed=buildTrends(map,adds,drops,now);
assert.equal(feed.players.find(p=>p.id==='1').net,4400000);
assert.equal(feed.players.find(p=>p.id==='2').net,-1100000);
assert.equal(feed.players.find(p=>p.id==='DET').net,700);
assert.equal(feed.players.find(p=>p.id==='3').net,0);
assert.ok(validTrendFeed(feed,now));
assert.equal(validTrendFeed(feed,now+3*3600000),false);
assert.throws(()=>buildTrends(map,[{player_id:'1',count:-1}],drops,now));
assert.throws(()=>buildTrends(map,[{player_id:'missing',count:5}],drops,now));
assert.throws(()=>buildTrends(map,Array.from({length:TREND_LIMIT},(_,i)=>({player_id:String(i),count:1})),drops,now));
assert.throws(()=>buildTrends(map,[{player_id:'1',count:1},{player_id:'1',count:2}],drops,now));
const calls=[];
const fresh=await collectTrends({previousMap:map,now,request:async url=>{calls.push(url);return url.includes('/add?')?adds:drops}});
assert.equal(calls.length,2,'Reuse the daily mapping; only request two trend feeds');
assert.ok(calls.every(url=>url.includes('lookback_hours=24')&&url.includes('limit=10000')));
assert.equal(fresh.data.players[0].net,4400000);

const runtime=await readFile('scripts/player-stat-extras.js','utf8');
const client=runtime.slice(0,runtime.indexOf('  // Ownership is current ESPN'));
assert.ok(client.includes('function hj40SetSleeperFeed'));
const context=vm.createContext({Date,Map,Set,Number,Error,console,setInterval:()=>0,hj40Pos:p=>p,hjNorm:s=>s.toLowerCase().replace(/[^a-z0-9]/g,''),pcBaseName:s=>s,pcTeam:s=>s});
vm.runInContext(client,context);
assert.equal(context.hj40TrendCount(5500000),'+5.5M');
assert.equal(context.hj40TrendCount(-1100000),'-1.1M');
assert.equal(context.hj40TrendCount(1500),'+1.5K');
assert.equal(context.hj40TrendCount(27),'+27');
assert.equal(context.hj40TrendCount(0),'0');
assert.equal(context.hj40TrendCount(null),'—');
assert.equal(context.hj40TrendCount(999999),'+1M');
context.hj40SetSleeperFeed(feed);
assert.equal(context.hj40SleeperRow({id:1001,position:'RB'}).net,4400000);
assert.equal(context.hj40SleeperRow({id:-16008,position:'D/ST',team:'DET'}).net,700);
assert.equal(context.hj40SleeperRow({id:999999,name:'Test Player 1',position:'RB'}).net,-1100000);
assert.equal(context.hj40SleeperRow({id:999999,name:'Unknown',position:'RB'}),null);
assert.throws(()=>context.hj40SetSleeperFeed({...feed,generatedAt:now-3*3600000}));
assert.throws(()=>context.hj40SetSleeperFeed({...feed,players:[{...feed.players[0],net:999}]}));
console.log('PASS: Sleeper net counts, full-pool request, daily map reuse, identities including DST, stale/malformed data, and K/M formatting.');
